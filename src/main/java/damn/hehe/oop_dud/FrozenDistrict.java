class ProductItem {
    float Price;
    int Quantity = 0;
	int id = FrozenDistrict.productId++;
    String Name;
    javax.swing.JLabel PriceLabel;
    javax.swing.JButton ProductButton;
    
    ProductItem (float price, int quantity, String name, javax.swing.JLabel priceLabel, javax.swing.JButton productButton) 
    {
        Name = name;
        Price = price;
        Quantity = quantity;
        PriceLabel = priceLabel;
        ProductButton = productButton;
    }
    
    float getSubtotal () {
        return Price * (float)Quantity;
    }
    
    String getTextPrice () {
        return  "₱ " + Price;
    }
    
    void afterInit () {
        PriceLabel.setText(this.getTextPrice());
    }

	void quantityUpdate () {
		String result = (Quantity <= 0 ? 
				this.getTextPrice() : 
				this.getTextPrice() + " * " + Quantity);
		PriceLabel.setText(result);
		FrozenDistrict.updatePickedList();
		FrozenDistrict.showToOrderList();
	}

    void productAction () {
		try {
			String input = JOptionPane.showInputDialog("Enter quantity: ");
			if (input == null) return;

			int getQuantity = Integer.parseInt(input);
			if (getQuantity < 0) throw new Exception("Invalid range.");
			Quantity = getQuantity;
			quantityUpdate();
		} catch (Exception e) {
			JOptionPane.showMessageDialog(null, "Invalid quantity value.", "Error quantity", JOptionPane.ERROR_MESSAGE);
		}
    }
}

